# -*- coding: utf-8 -*-
"""
reassemble.py 가 만든 projects/<proj>/ 를 Hardhat 2 로도 컴파일하는 게이트.

Hardhat 2 는 remapping 을 지원하지 않는다. 그래서 각 프로젝트의 remappings.txt 를 읽어
`projects/<proj>/node_modules/<prefix>` 를 **junction**(디렉토리 바로가기)으로 만들어, Hardhat 이 자기 node_modules 에서
찾는 것처럼 같은 파일(oz3/oz4 등)을 보게 한다. 파일 복사·소스 수정 없음.

컴파일러: 2021~22년 코드의 pragma 를 덮는 버전 목록을 주고 Hardhat 이 파일별로 고르게 한다. forge 게이트에서
solc 를 핀한 프로젝트(reassemble_report.json 의 solc != auto, 예: w42 SPDX 문제)는 그 버전 하나만 준다.

출력: projects/<proj>/hardhat.config.js, node_modules/(junction), hh-artifacts/, hh-cache/, hh-build.log
      hardhat_gate_report.json

사용:
  .venv/Scripts/python.exe evaluation/Dataset/hardhat_gate.py            # 전체
  .venv/Scripts/python.exe evaluation/Dataset/hardhat_gate.py --only w45
"""
import argparse
import json
import os
import pathlib
import re
import shutil
import subprocess
import sys
import _winapi

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

DS = pathlib.Path(__file__).resolve().parent
ROOT = DS.parents[1]
PROJ = DS / "projects"
HH_DIR = ROOT / "evaluation" / "hardhat"          # hardhat 2.29.1 설치 위치 (npx 실행 cwd)

ERA_SOLC = ["0.4.26", "0.5.17", "0.6.6", "0.6.8", "0.6.12", "0.7.4", "0.7.6",
            "0.8.1", "0.8.3", "0.8.4", "0.8.6", "0.8.7", "0.8.9", "0.8.10", "0.8.11", "0.8.12", "0.8.13"]


def _is_reparse(p: pathlib.Path) -> bool:
    import stat
    try:
        return bool(p.lstat().st_file_attributes & stat.FILE_ATTRIBUTE_REPARSE_POINT)
    except FileNotFoundError:
        return False


MANIFEST = ".hh_gate_manifest.json"


def clear_junctions(nm: pathlib.Path):
    """이 스크립트가 만든 것만 manifest 대로 제거한다. junction 은 **링크만** 삭제(rmdir)하고 대상 내용은
    절대 건드리지 않는다. manifest 에 없는 실제 파일을 만나면 멈춘다."""
    if not nm.exists():
        return
    mf = nm / MANIFEST
    if not mf.exists():
        raise RuntimeError(f"{nm} exists without {MANIFEST} — not created by this script, refusing to touch")
    m = json.loads(mf.read_text(encoding="utf-8"))
    for j in m["junctions"]:
        p = pathlib.Path(j)
        if p.exists() or _is_reparse(p):
            if not _is_reparse(p):
                raise RuntimeError(f"manifest junction is not a reparse point: {p}")
            p.rmdir()
    for f in m["files"]:
        pathlib.Path(f).unlink(missing_ok=True)
    mf.unlink()
    for d in sorted((d for d in nm.rglob("*") if d.is_dir() and not _is_reparse(d)), key=lambda x: -len(x.parts)):
        d.rmdir()                              # 이제 비어 있어야 한다 (아니면 rmdir 가 실패한다)
    nm.rmdir()


def make_junctions(pdir: pathlib.Path) -> list[str]:
    """remappings.txt 의 `prefix=target` 마다 node_modules/<prefix> 를 만든다.
    Hardhat 2 는 `node_modules/<패키지>/package.json` 이 있어야 라이브러리로 인식한다(HH411). 대상이 패키지 루트
    (package.json 보유)면 그 폴더로 junction 하나. 대상이 하위 폴더(solmate/src, 복원 bentobox-sdk)면 node_modules/<prefix>
    를 실제 폴더로 만들고 생성 package.json + 대상의 각 하위 폴더 junction 을 넣는다(최상위 .sol 은 하드링크)."""
    nm = pdir / "node_modules"
    clear_junctions(nm)
    made, junctions, files = [], [], []
    rm = pdir / "remappings.txt"
    if not rm.exists():
        return made
    for line in rm.read_text(encoding="utf-8").splitlines():
        if "=" not in line:
            continue
        prefix, target = line.split("=", 1)
        if target.rstrip("/") == "src":
            # 저장소 루트 기준 import (reassemble.ROOT_IMPORT_PREFIX, w17 `contracts/...`). Hardhat 은 루트 기준 import 를
            # 로컬 파일로 해석하므로, node_modules 링크가 아니라 프로젝트 루트에 `<prefix>` → src junction 을 두고
            # sources 를 그쪽으로 잡는다 (node_modules 로 하면 같은 파일이 두 source name 이 된다 — HH415).
            link = pdir / prefix.rstrip("/")
            _winapi.CreateJunction(str((pdir / "src").resolve()), str(link))
            junctions.append(str(link))
            made.append(f"{prefix} -> src (sources root)")
            continue
        link = nm / prefix.rstrip("/")
        tgt = (pdir / target).resolve()
        if not tgt.is_dir():
            raise FileNotFoundError(f"{pdir.name}: remapping target missing: {target}")
        link.parent.mkdir(parents=True, exist_ok=True)
        if (tgt / "package.json").exists():
            _winapi.CreateJunction(str(tgt), str(link))
            junctions.append(str(link))
            made.append(f"{prefix} -> {tgt}")
            continue
        link.mkdir()
        pj = link / "package.json"
        pj.write_text(json.dumps({"name": prefix.rstrip("/"), "version": "0.0.0",
                                  "description": "generated by hardhat_gate.py (remapping wrapper)"}), encoding="utf-8")
        files.append(str(pj))
        for c in tgt.iterdir():
            dst = link / c.name
            if c.is_dir():
                _winapi.CreateJunction(str(c), str(dst))
                junctions.append(str(dst))
            elif c.suffix == ".sol":
                os.link(c, dst)
                files.append(str(dst))
        made.append(f"{prefix} -> {tgt} (wrapper)")
    if made:
        nm.mkdir(exist_ok=True)
        (nm / MANIFEST).write_text(json.dumps({"junctions": junctions, "files": files}, indent=1), encoding="utf-8")
    return made


def write_config(pdir: pathlib.Path, versions: list[str], sources: str = "./src"):
    comps = ",\n      ".join(f'{{ version: "{v}" }}' for v in versions)
    cfg = f"""// generated by evaluation/Dataset/hardhat_gate.py
module.exports = {{
  solidity: {{
    compilers: [
      {comps}
    ],
  }},
  paths: {{ sources: "{sources}", artifacts: "./hh-artifacts", cache: "./hh-cache" }},
}};
"""
    (pdir / "hardhat.config.js").write_text(cfg, encoding="utf-8")


def run_hardhat(pdir: pathlib.Path):
    cmd = ["npx", "hardhat", "compile", "--config", str(pdir / "hardhat.config.js")]
    proc = subprocess.run(cmd, cwd=HH_DIR, capture_output=True, text=True, encoding="utf-8",
                          errors="replace", shell=True)
    text = proc.stdout + proc.stderr
    (pdir / "hh-build.log").write_text(text, encoding="utf-8")
    errs = [l.strip() for l in text.splitlines() if re.search(r"Error|HH\d+", l)]
    return proc.returncode == 0, errs[:3]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only")
    a = ap.parse_args()
    rep = json.loads((DS / "reassemble_report.json").read_text(encoding="utf-8"))
    out = {}
    ok_cases = total = 0
    for pkey in sorted(rep):
        if a.only and pkey != a.only:
            continue
        pdir = PROJ / pkey
        solc = rep[pkey].get("solc", "auto")
        versions = [solc] if solc not in (None, "auto") else ERA_SOLC
        juncs = make_junctions(pdir)
        root = next((j.split(" -> ")[0].rstrip("/") for j in juncs if j.endswith("(sources root)")), None)
        write_config(pdir, versions, f"./{root}" if root else "./src")
        for d in ("hh-artifacts", "hh-cache"):
            if (pdir / d).exists():
                shutil.rmtree(pdir / d)
        ok, errs = run_hardhat(pdir)
        n = len(rep[pkey]["cases"])
        total += n
        ok_cases += n if ok else 0
        out[pkey] = {"cases": rep[pkey]["cases"], "ok": ok, "errors": errs, "junctions": juncs,
                     "compilers": versions, "forge_ok": rep[pkey].get("build_ok")}
        print(f"{pkey:<20} {'OK  ' if ok else 'FAIL'} ({n} cases)" + ("" if ok else "  " + " | ".join(errs)))
    print(f"\nHardhat 컴파일 통과 케이스: {ok_cases}/{total}")
    rpath = DS / "hardhat_gate_report.json"
    if a.only and rpath.exists():            # --only 는 그 항목만 갱신
        merged = json.loads(rpath.read_text(encoding="utf-8"))
        merged.update(out)
        out = merged
    rpath.write_text(json.dumps(out, indent=2, ensure_ascii=False), encoding="utf-8")


if __name__ == "__main__":
    main()
